from fastapi import FastAPI, UploadFile, File, HTTPException
import numpy as np
import cv2
import torch

app = FastAPI(
    title="VisionPort Traffic Detection",
    description="Traffic object detection using YOLO and GPU",
    version="1.0"
)

@app.get("/")
def home():
    return {
        "project": "VisionPort",
        "status": "Running",
        "model": "YOLOv8 Nano"
    }

@app.get("/health")
def health():
    return {
        "api": "Active",
        "gpu_available": torch.cuda.is_available()
    }

@app.post("/detect")
async def detect_traffic(file: UploadFile = File(...)):

    contents = await file.read()

    image_array = np.frombuffer(contents, dtype=np.uint8)
    image = cv2.imdecode(image_array, cv2.IMREAD_COLOR)

    if image is None:
        raise HTTPException(status_code=400, detail="Invalid image")

    results = model.predict(
        source=image,
        device=device,
        conf=0.40,
        verbose=False
    )

    detections = []
    counts = {}

    for box in results[0].boxes:
        class_id = int(box.cls[0])
        label = model.names[class_id]
        confidence = float(box.conf[0])

        if label not in ["person", "bicycle", "car", "motorcycle", "bus", "truck"]:
            continue

        coordinates = box.xyxy[0].cpu().tolist()

        counts[label] = counts.get(label, 0) + 1

        detections.append({
            "class": label,
            "confidence": round(confidence, 3),
            "bounding_box": coordinates
        })

    return {
        "project": "VisionPort",
        "filename": file.filename,
        "total_objects": len(detections),
        "object_counts": counts,
        "detections": detections
    }

