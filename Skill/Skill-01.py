# 1. IMPORT LIBRARIES
import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
import os

from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    ConfusionMatrixDisplay
)

from google.colab import files
from PIL import Image

print("=" * 65)
print("VISIONPORT - DEEP LEARNING SYSTEM LIFECYCLE")
print("=" * 65)

print("TensorFlow Version:", tf.__version__)

# 2. DATASET COLLECTION
print("\n1. DATASET COLLECTION")

# Load CIFAR-10 dataset
(x_train, y_train), (x_test, y_test) = (
    tf.keras.datasets.cifar10.load_data()
)

class_names = [
    'Airplane', 'Automobile', 'Bird', 'Cat', 'Deer',
    'Dog', 'Frog', 'Horse', 'Ship', 'Truck'
]

print("Training images:", x_train.shape)
print("Testing images:", x_test.shape)
print("Number of classes:", len(class_names))

# 3. DATASET VISUALIZATION
print("\n2. DATASET VISUALIZATION")

plt.figure(figsize=(10, 6))

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(x_train[i])
    plt.title(class_names[int(y_train[i][0])])
    plt.axis("off")

plt.suptitle("VisionPort - Sample Dataset")
plt.tight_layout()
plt.show()

# 4. DATA PREPROCESSING
print("\n3. DATA PREPROCESSING")

# Normalize image pixel values
x_train = x_train.astype("float32") / 255.0
x_test = x_test.astype("float32") / 255.0

y_train = y_train.flatten()
y_test = y_test.flatten()

print("Normalization completed!")
print("Training data:", x_train.shape)
print("Testing data:", x_test.shape)

# 5. MODEL DEVELOPMENT
print("\n4. CNN MODEL DEVELOPMENT")

model = tf.keras.Sequential([

    tf.keras.layers.Input(shape=(32, 32, 3)),

    tf.keras.layers.Conv2D(
        32, (3, 3), activation="relu"
    ),
    tf.keras.layers.MaxPooling2D((2, 2)),

    tf.keras.layers.Conv2D(
        64, (3, 3), activation="relu"
    ),
    tf.keras.layers.MaxPooling2D((2, 2)),

    tf.keras.layers.Conv2D(
        128, (3, 3), activation="relu"
    ),

    tf.keras.layers.Flatten(),

    tf.keras.layers.Dense(128, activation="relu"),

    tf.keras.layers.Dropout(0.3),

    tf.keras.layers.Dense(10, activation="softmax")
])

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

model.summary()

# 6. MODEL TRAINING
print("\n5. MODEL TRAINING")

history = model.fit(
    x_train,
    y_train,
    epochs=10,
    batch_size=64,
    validation_split=0.2,
    verbose=1
)

print("\nModel training completed!")

# 7. MODEL EVALUATION
print("\n6. MODEL EVALUATION")

test_loss, test_accuracy = model.evaluate(
    x_test, y_test, verbose=0
)

print("Test Loss:", round(test_loss, 4))
print("Test Accuracy:", round(test_accuracy * 100, 2), "%")

# 8. ACCURACY AND LOSS GRAPHS
print("\n7. TRAINING PERFORMANCE VISUALIZATION")

plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.plot(history.history["accuracy"], label="Training Accuracy")
plt.plot(history.history["val_accuracy"], label="Validation Accuracy")
plt.title("Model Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.legend()
plt.grid()

plt.subplot(1, 2, 2)
plt.plot(history.history["loss"], label="Training Loss")
plt.plot(history.history["val_loss"], label="Validation Loss")
plt.title("Model Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()
plt.grid()

plt.tight_layout()
plt.show()

# 9. PREDICTIONS ON TEST DATA
print("\n8. MODEL PREDICTION")

predictions = model.predict(x_test, verbose=0)
predicted_labels = np.argmax(predictions, axis=1)

# Display sample predictions
plt.figure(figsize=(12, 7))

for i in range(10):
    plt.subplot(2, 5, i + 1)

    plt.imshow(x_test[i])

    actual = class_names[y_test[i]]
    predicted = class_names[predicted_labels[i]]

    plt.title(
        f"Actual: {actual}\nPredicted: {predicted}"
    )

    plt.axis("off")

plt.tight_layout()
plt.show()

# 10. CLASSIFICATION REPORT
print("\n9. CLASSIFICATION REPORT")

print(classification_report(
y_test,
    predicted_labels,
    labels=list(range(10)),
    target_names=class_names,
    zero_division=0
))

# 11. CONFUSION MATRIX
print("\n10. CONFUSION MATRIX")

cm = confusion_matrix(y_test, predicted_labels)

display = ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=class_names
)

fig, ax = plt.subplots(figsize=(10, 10))

display.plot(
    ax=ax,
    xticks_rotation=45,
    cmap="Blues",
    colorbar=False
)

plt.title("VisionPort - Confusion Matrix")
plt.tight_layout()
plt.show()

# 12. CUSTOM IMAGE PREDICTION
print("\n11. UPLOAD YOUR OWN IMAGE")

uploaded = files.upload()

for filename in uploaded.keys():

    try:
        image = Image.open(filename).convert("RGB")

        # Resize to model input dimensions
        image = image.resize((32, 32))

        image_array = np.array(image).astype("float32") / 255.0

        image_array = np.expand_dims(image_array, axis=0)

        # Predict
        result = model.predict(image_array, verbose=0)

        predicted_class = np.argmax(result[0])
        confidence = result[0][predicted_class] * 100

        print("\nImage:", filename)
        print("Predicted Class:", class_names[predicted_class])
        print("Confidence:", round(float(confidence), 2), "%")

        plt.imshow(Image.open(filename))
        plt.title(
            f"Prediction: {class_names[predicted_class]}\n"
            f"Confidence: {confidence:.2f}%"
        )
        plt.axis("off")
        plt.show()

    except Exception as e:
        print("Image processing error:", e)

# 13. SAVE TRAINED MODEL
print("\n12. MODEL DEPLOYMENT AND SAVING")

os.makedirs("VisionPort_Output", exist_ok=True)

model.save("VisionPort_Output/visionport_model.keras")

print("Model saved successfully!")

# Save class names
with open("VisionPort_Output/class_names.txt", "w") as f:
    f.write("\n".join(class_names))

print("Class names saved successfully!")

